-- 6.1 SERVICIO: cada servicio pertenece a un alojamiento específico.
CREATE TABLE servicio (
  id_servicio     NUMBER(6)      GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_alojamiento  NUMBER(6)      NOT NULL,
  nombre          VARCHAR2(60)   NOT NULL,
  descripcion     VARCHAR2(300),
  precio          NUMBER(12,2)   NOT NULL,
  activo          CHAR(1)        DEFAULT 'S' NOT NULL,
  CONSTRAINT pk_servicio             PRIMARY KEY (id_servicio),
  CONSTRAINT fk_servicio_alojamiento FOREIGN KEY (id_alojamiento)
                                     REFERENCES alojamiento (id_alojamiento),
  -- El "Desayuno" del Hotel X y el del Hotel Y son servicios distintos,
  -- pero un alojamiento no repite el nombre de un servicio.
  CONSTRAINT uq_servicio_nombre      UNIQUE (id_alojamiento, nombre),
  CONSTRAINT uq_servicio_aloj        UNIQUE (id_servicio, id_alojamiento),
  CONSTRAINT ck_servicio_precio      CHECK (precio > 0),
  CONSTRAINT ck_servicio_activo      CHECK (activo IN ('S','N'))
);
COMMENT ON TABLE servicio IS 'Servicio adicional (desayuno, tour, transporte...) ofrecido por un alojamiento concreto, con su precio.';

-- 6.2 RESERVA_SERVICIO: servicios contratados en una reserva, con cantidad.
CREATE TABLE reserva_servicio (
  id_reserva_servicio NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_reserva          NUMBER(10)    NOT NULL,
  id_alojamiento      NUMBER(6)     NOT NULL,
  id_servicio         NUMBER(6)     NOT NULL,
  cantidad            NUMBER(3)     NOT NULL,
  precio_unitario     NUMBER(12,2)  NOT NULL,
  subtotal            NUMBER(14,2)  GENERATED ALWAYS AS (cantidad * precio_unitario) VIRTUAL,
  CONSTRAINT pk_reserva_servicio  PRIMARY KEY (id_reserva_servicio),
  -- Mismo patrón de FK compuestas: solo se pueden contratar servicios del
  -- alojamiento de la reserva.
  CONSTRAINT fk_rs_reserva        FOREIGN KEY (id_reserva, id_alojamiento)
                                  REFERENCES reserva (id_reserva, id_alojamiento)
                                  ON DELETE CASCADE,
  CONSTRAINT fk_rs_servicio       FOREIGN KEY (id_servicio, id_alojamiento)
                                  REFERENCES servicio (id_servicio, id_alojamiento),
  CONSTRAINT uq_rs_reserva_serv   UNIQUE (id_reserva, id_servicio),
  CONSTRAINT ck_rs_cantidad       CHECK (cantidad > 0),
  CONSTRAINT ck_rs_precio         CHECK (precio_unitario > 0)
);
COMMENT ON TABLE  reserva_servicio                 IS 'Servicios contratados dentro de una reserva; la cantidad permite pedir varias unidades.';
COMMENT ON COLUMN reserva_servicio.precio_unitario IS 'Precio del servicio en el momento de contratarlo (copia congelada de SERVICIO.PRECIO).';
COMMENT ON COLUMN reserva_servicio.subtotal        IS 'Columna virtual = cantidad * precio_unitario.';

/* =============================================================================
   7. PAGOS
   ============================================================================= */
CREATE TABLE pago (
  id_pago           NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_reserva        NUMBER(10)    NOT NULL,
  fecha_pago        DATE          NOT NULL,
  concepto          VARCHAR2(10)  NOT NULL,
  monto             NUMBER(14,2)  NOT NULL,
  metodo            VARCHAR2(16)  NOT NULL,
  estado            VARCHAR2(12)  NOT NULL,
  monto_reembolsado NUMBER(14,2),
  fecha_reembolso   DATE,
  CONSTRAINT pk_pago            PRIMARY KEY (id_pago),
  CONSTRAINT fk_pago_reserva    FOREIGN KEY (id_reserva)
                                REFERENCES reserva (id_reserva),
  CONSTRAINT ck_pago_monto      CHECK (monto > 0),
  CONSTRAINT ck_pago_concepto   CHECK (concepto IN ('ANTICIPO','SALDO','TOTAL')),
  CONSTRAINT ck_pago_metodo     CHECK (metodo IN ('TARJETA_CREDITO','TARJETA_DEBITO','PSE',
                                                  'TRANSFERENCIA','EFECTIVO')),
  CONSTRAINT ck_pago_estado     CHECK (estado IN ('EXITOSO','FALLIDO','PENDIENTE','REEMBOLSADO')),
  -- Un reembolso nunca supera lo pagado y solo existe en pagos REEMBOLSADOS.
  CONSTRAINT ck_pago_reembolso  CHECK (
       (estado = 'REEMBOLSADO'  AND monto_reembolsado IS NOT NULL
                                AND monto_reembolsado > 0
                                AND monto_reembolsado <= monto
                                AND fecha_reembolso IS NOT NULL
                                AND fecha_reembolso >= TRUNC(fecha_pago))
    OR (estado <> 'REEMBOLSADO' AND monto_reembolsado IS NULL
                                AND fecha_reembolso IS NULL))
);
COMMENT ON TABLE  pago                   IS 'Abonos de una reserva (anticipo, saldo o pago total). La reserva está pagada cuando sus pagos EXITOSOS cubren estadía + servicios.';
COMMENT ON COLUMN pago.estado            IS 'REEMBOLSADO: el pago fue exitoso y luego se devolvió monto_reembolsado (80 % si se canceló con más de 5 días).';
COMMENT ON COLUMN pago.monto_reembolsado IS 'Valor devuelto al cliente; monto - monto_reembolsado es lo que retiene el alojamiento.';

/* =============================================================================
   8. RESEÑAS
   ============================================================================= */
CREATE TABLE resena (
  id_resena     NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_reserva    NUMBER(10)     NOT NULL,
  calificacion  NUMBER(1)      NOT NULL,
  comentario    VARCHAR2(500),
  fecha_resena  DATE           NOT NULL,
  CONSTRAINT pk_resena               PRIMARY KEY (id_resena),
  -- La reseña nace de una reserva: así se sabe qué cliente opina sobre qué
  -- alojamiento y se garantiza que estuvo allí. Una reseña por reserva.
  CONSTRAINT fk_resena_reserva       FOREIGN KEY (id_reserva)
                                     REFERENCES reserva (id_reserva),
  CONSTRAINT uq_resena_reserva       UNIQUE (id_reserva),
  CONSTRAINT ck_resena_calificacion  CHECK (calificacion BETWEEN 1 AND 5)
);
COMMENT ON TABLE  resena            IS 'Opinión del cliente sobre el alojamiento tras una reserva COMPLETADA (validación de estado: disparador en Entrega 2).';
COMMENT ON COLUMN resena.comentario IS 'Opcional.';

/* =============================================================================
   9. VISTA DE APOYO: valor total y estado de pago de cada reserva
      total = estadía (todas las habitaciones) + servicios
      pagada = SUM(pagos EXITOSOS) >= total
   ============================================================================= */
CREATE OR REPLACE VIEW vw_valor_reserva AS
SELECT r.id_reserva,
       r.id_alojamiento,
       r.estado,
       NVL(h.valor_estadia, 0)                          AS valor_estadia,
       NVL(s.valor_servicios, 0)                        AS valor_servicios,
       NVL(h.valor_estadia, 0) + NVL(s.valor_servicios, 0) AS valor_total,
       NVL(p.pagado_exitoso, 0)                         AS pagado_exitoso,
       NVL(p.retenido_cancelacion, 0)                   AS retenido_cancelacion,
       CASE WHEN NVL(p.pagado_exitoso, 0) >= NVL(h.valor_estadia, 0) + NVL(s.valor_servicios, 0)
            THEN 'S' ELSE 'N' END                       AS pagada
  FROM reserva r
  LEFT JOIN (SELECT id_reserva, SUM(valor_estadia) AS valor_estadia
               FROM reserva_habitacion GROUP BY id_reserva) h
         ON h.id_reserva = r.id_reserva
  LEFT JOIN (SELECT id_reserva, SUM(subtotal) AS valor_servicios
               FROM reserva_servicio GROUP BY id_reserva) s
         ON s.id_reserva = r.id_reserva
  LEFT JOIN (SELECT id_reserva,
                    SUM(CASE WHEN estado = 'EXITOSO' THEN monto END)                      AS pagado_exitoso,
                    SUM(CASE WHEN estado = 'REEMBOLSADO' THEN monto - monto_reembolsado END) AS retenido_cancelacion
               FROM pago GROUP BY id_reserva) p
         ON p.id_reserva = r.id_reserva;

COMMENT ON TABLE vw_valor_reserva IS 'Valor de estadía, servicios, total y si la reserva está pagada (pagos EXITOSOS >= total).';

