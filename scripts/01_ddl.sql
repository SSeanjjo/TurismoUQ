-- 4.1 CLIENTE
CREATE TABLE cliente (
  id_cliente        NUMBER(8)      GENERATED BY DEFAULT ON NULL AS IDENTITY,
  tipo_documento    VARCHAR2(3)    NOT NULL,
  numero_documento  VARCHAR2(20)   NOT NULL,
  nombres           VARCHAR2(60)   NOT NULL,
  apellidos         VARCHAR2(60)   NOT NULL,
  correo            VARCHAR2(120)  NOT NULL,
  telefono          VARCHAR2(20)   NOT NULL,
  id_ciudad_origen  NUMBER(5)      NOT NULL,
  fecha_registro    DATE           NOT NULL,
  CONSTRAINT pk_cliente            PRIMARY KEY (id_cliente),
  CONSTRAINT fk_cliente_ciudad     FOREIGN KEY (id_ciudad_origen)
                                   REFERENCES ciudad (id_ciudad),
  CONSTRAINT uq_cliente_documento  UNIQUE (tipo_documento, numero_documento),
  CONSTRAINT uq_cliente_correo     UNIQUE (correo),
  CONSTRAINT ck_cliente_tipo_doc   CHECK (tipo_documento IN ('CC','CE','PAS')),
  CONSTRAINT ck_cliente_correo     CHECK (correo LIKE '%_@_%._%')
);
COMMENT ON TABLE  cliente                IS 'Persona que hace reservas. Un cliente puede tener muchas reservas en el tiempo.';
COMMENT ON COLUMN cliente.tipo_documento IS 'CC cédula de ciudadanía, CE cédula de extranjería, PAS pasaporte.';

-- 4.2 USUARIO_SISTEMA: usuarios internos de la plataforma.
--     Los encargados y recepcionistas pertenecen a UN alojamiento; los roles de
--     plataforma (administrador, gerente, auditor) no tienen alojamiento.
--     Esto es la base de la seguridad por filas de la Entrega 3.
CREATE TABLE usuario_sistema (
  id_usuario      NUMBER(5)      GENERATED BY DEFAULT ON NULL AS IDENTITY,
  username        VARCHAR2(30)   NOT NULL,
  nombre_completo VARCHAR2(100)  NOT NULL,
  correo          VARCHAR2(120)  NOT NULL,
  rol             VARCHAR2(20)   NOT NULL,
  id_alojamiento  NUMBER(6),
  activo          CHAR(1)        DEFAULT 'S' NOT NULL,
  fecha_creacion  DATE           DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_usuario_sistema      PRIMARY KEY (id_usuario),
  CONSTRAINT fk_usuario_alojamiento  FOREIGN KEY (id_alojamiento)
                                     REFERENCES alojamiento (id_alojamiento),
  CONSTRAINT uq_usuario_username     UNIQUE (username),
  CONSTRAINT uq_usuario_correo       UNIQUE (correo),
  CONSTRAINT ck_usuario_username     CHECK (username = UPPER(username)),
  CONSTRAINT ck_usuario_rol          CHECK (rol IN ('ADMIN_PLATAFORMA','GERENTE','AUDITOR',
                                                    'ADMIN_ALOJAMIENTO','RECEPCION')),
  -- Rol de alojamiento <=> tiene alojamiento asignado.
  CONSTRAINT ck_usuario_rol_aloj     CHECK (
       (rol IN ('ADMIN_ALOJAMIENTO','RECEPCION')          AND id_alojamiento IS NOT NULL)
    OR (rol IN ('ADMIN_PLATAFORMA','GERENTE','AUDITOR')   AND id_alojamiento IS NULL)),
  CONSTRAINT ck_usuario_activo       CHECK (activo IN ('S','N'))
);
COMMENT ON TABLE  usuario_sistema          IS 'Usuarios internos de TurismoUQ con su rol. Los de alojamiento solo gestionan su propio alojamiento.';
COMMENT ON COLUMN usuario_sistema.username IS 'Debe coincidir con el usuario de Oracle (en mayúsculas) para filtrar por SYS_CONTEXT(''USERENV'',''SESSION_USER'').';

/* =============================================================================
   5. RESERVAS  (decisión de diseño 1)
