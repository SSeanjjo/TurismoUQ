-- 5.1 RESERVA: encabezado. Una reserva pertenece a un cliente y a UN alojamiento.
CREATE TABLE reserva (
  id_reserva        NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_cliente        NUMBER(8)      NOT NULL,
  id_alojamiento    NUMBER(6)      NOT NULL,
  fecha_reserva     DATE           NOT NULL,
  fecha_checkin     DATE           NOT NULL,
  fecha_checkout    DATE           NOT NULL,
  estado            VARCHAR2(12)   DEFAULT 'PENDIENTE' NOT NULL,
  fecha_cancelacion DATE,
  observaciones     VARCHAR2(300),
  CONSTRAINT pk_reserva              PRIMARY KEY (id_reserva),
  CONSTRAINT fk_reserva_cliente      FOREIGN KEY (id_cliente)
                                     REFERENCES cliente (id_cliente),
  CONSTRAINT fk_reserva_alojamiento  FOREIGN KEY (id_alojamiento)
                                     REFERENCES alojamiento (id_alojamiento),
  -- Llave candidata usada por las FK compuestas de las líneas.
  CONSTRAINT uq_reserva_aloj         UNIQUE (id_reserva, id_alojamiento),
  CONSTRAINT ck_reserva_estado       CHECK (estado IN ('PENDIENTE','CONFIRMADA','CANCELADA','COMPLETADA')),
  CONSTRAINT ck_reserva_dias         CHECK (fecha_checkin = TRUNC(fecha_checkin)
                                            AND fecha_checkout = TRUNC(fecha_checkout)),
  CONSTRAINT ck_reserva_fechas       CHECK (fecha_checkout > fecha_checkin),
  CONSTRAINT ck_reserva_max_noches   CHECK (fecha_checkout - fecha_checkin <= 30),
  CONSTRAINT ck_reserva_anticipada   CHECK (TRUNC(fecha_reserva) <= fecha_checkin),
  -- Solo las canceladas tienen fecha de cancelación, y es posterior a la reserva.
  CONSTRAINT ck_reserva_cancelacion  CHECK (
       (estado = 'CANCELADA'  AND fecha_cancelacion IS NOT NULL
                              AND fecha_cancelacion >= TRUNC(fecha_reserva))
    OR (estado <> 'CANCELADA' AND fecha_cancelacion IS NULL))
);
COMMENT ON TABLE  reserva                   IS 'Encabezado de la reserva: cliente, alojamiento, rango general de fechas y estado. El detalle de habitaciones está en RESERVA_HABITACION.';
COMMENT ON COLUMN reserva.fecha_checkin     IS 'Inicio del rango general: la menor fecha de llegada de sus líneas.';
COMMENT ON COLUMN reserva.fecha_checkout    IS 'Fin del rango general: la mayor fecha de salida de sus líneas.';
COMMENT ON COLUMN reserva.fecha_cancelacion IS 'Define el derecho a reembolso: más de 5 días antes del check-in => 80 %.';

-- 5.2 RESERVA_HABITACION: línea de reserva (una por habitación reservada).
CREATE TABLE reserva_habitacion (
  id_reserva_habitacion NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_reserva            NUMBER(10)    NOT NULL,
  id_alojamiento        NUMBER(6)     NOT NULL,
  id_habitacion         NUMBER(8)     NOT NULL,
  fecha_checkin         DATE          NOT NULL,
  fecha_checkout        DATE          NOT NULL,
  num_huespedes         NUMBER(2)     NOT NULL,
  valor_estadia         NUMBER(14,2)  NOT NULL,
  CONSTRAINT pk_reserva_habitacion  PRIMARY KEY (id_reserva_habitacion),
  -- FK compuesta: la línea pertenece a una reserva DE ESE alojamiento...
  CONSTRAINT fk_rh_reserva          FOREIGN KEY (id_reserva, id_alojamiento)
                                    REFERENCES reserva (id_reserva, id_alojamiento)
                                    ON DELETE CASCADE,
  -- ...y la habitación es DE ESE MISMO alojamiento.
  CONSTRAINT fk_rh_habitacion       FOREIGN KEY (id_habitacion, id_alojamiento)
                                    REFERENCES habitacion (id_habitacion, id_alojamiento),
  CONSTRAINT uq_rh_reserva_hab      UNIQUE (id_reserva, id_habitacion),
  CONSTRAINT ck_rh_dias             CHECK (fecha_checkin = TRUNC(fecha_checkin)
                                           AND fecha_checkout = TRUNC(fecha_checkout)),
  CONSTRAINT ck_rh_fechas           CHECK (fecha_checkout > fecha_checkin),
  CONSTRAINT ck_rh_huespedes        CHECK (num_huespedes > 0),
  CONSTRAINT ck_rh_valor            CHECK (valor_estadia >= 0)
);
COMMENT ON TABLE  reserva_habitacion               IS 'Detalle de la reserva: cada habitación con sus propias fechas (pueden diferir dentro del rango general).';
COMMENT ON COLUMN reserva_habitacion.id_alojamiento IS 'Redundancia controlada: participa en las dos FK compuestas que obligan a que todas las habitaciones sean del alojamiento de la reserva.';
COMMENT ON COLUMN reserva_habitacion.valor_estadia  IS 'Suma noche a noche de la tarifa vigente cada día, congelada al reservar (si la tarifa cambia después, la reserva no cambia).';

/* =============================================================================
   6. SERVICIOS COMPLEMENTARIOS
