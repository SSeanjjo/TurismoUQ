   TurismoUQ · Proyecto integrador Bases de Datos II · Universidad del Quindío
   Script 01 · DDL: tablas, restricciones, comentarios y vista de apoyo
   Motor: Oracle Database XE 21c
   Ejecución: como el usuario dueño del esquema, en SQL Developer (F5 "Ejecutar
   script") o SQL*Plus. Debe correr de arriba abajo sobre una base limpia; si las
   tablas ya existen, la sección 0 las elimina primero.

   Orden de creación (padres antes que hijas):
     MUNICIPIO, TIPO_ALOJAMIENTO, CIUDAD, ALOJAMIENTO, HABITACION, TEMPORADA,
     CALENDARIO, TARIFA, CLIENTE, USUARIO_SISTEMA, RESERVA, RESERVA_HABITACION,
     SERVICIO, RESERVA_SERVICIO, PAGO, RESENA
   Las 14 entidades del enunciado + 2 agregadas (CIUDAD y CALENDARIO).

   Convenciones de nombres de restricciones:
     pk_<tabla>   llave primaria        fk_<hija>_<padre>  llave foránea
     uq_<tabla>_x única                 ck_<tabla>_x       verificación
   ============================================================================= */

