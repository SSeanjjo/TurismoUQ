-- 2.1 ALOJAMIENTO
CREATE TABLE alojamiento (
  id_alojamiento      NUMBER(6)      GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_municipio        NUMBER(4)      NOT NULL,
  id_tipo_alojamiento NUMBER(3)      NOT NULL,
  nombre_comercial    VARCHAR2(100)  NOT NULL,
  direccion           VARCHAR2(150)  NOT NULL,
  estrellas           NUMBER(1)      NOT NULL,
  telefono            VARCHAR2(20)   NOT NULL,
  correo              VARCHAR2(100)  NOT NULL,
  fecha_registro      DATE           NOT NULL,
  activo              CHAR(1)        DEFAULT 'S' NOT NULL,
  CONSTRAINT pk_alojamiento             PRIMARY KEY (id_alojamiento),
  CONSTRAINT fk_alojamiento_municipio   FOREIGN KEY (id_municipio)
                                        REFERENCES municipio (id_municipio),
  CONSTRAINT fk_alojamiento_tipo        FOREIGN KEY (id_tipo_alojamiento)
                                        REFERENCES tipo_alojamiento (id_tipo_alojamiento),
  CONSTRAINT uq_alojamiento_nombre_mun  UNIQUE (nombre_comercial, id_municipio),
  CONSTRAINT uq_alojamiento_correo      UNIQUE (correo),
  CONSTRAINT ck_alojamiento_estrellas   CHECK (estrellas BETWEEN 1 AND 5),
  CONSTRAINT ck_alojamiento_correo      CHECK (correo LIKE '%_@_%._%'),
  CONSTRAINT ck_alojamiento_activo      CHECK (activo IN ('S','N'))
);
COMMENT ON TABLE  alojamiento           IS 'Establecimiento que ofrece habitaciones: pertenece a un municipio y a un tipo.';
COMMENT ON COLUMN alojamiento.estrellas IS 'Calificación de 1 a 5 que el propio alojamiento se autoasigna (no es la de las reseñas).';

-- 2.2 HABITACION
CREATE TABLE habitacion (
  id_habitacion     NUMBER(8)      GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_alojamiento    NUMBER(6)      NOT NULL,
  numero            VARCHAR2(10)   NOT NULL,
  tipo_habitacion   VARCHAR2(10)   NOT NULL,
  capacidad_maxima  NUMBER(2)      NOT NULL,
  descripcion       VARCHAR2(300),
  activa            CHAR(1)        DEFAULT 'S' NOT NULL,
  CONSTRAINT pk_habitacion             PRIMARY KEY (id_habitacion),
  CONSTRAINT fk_habitacion_alojamiento FOREIGN KEY (id_alojamiento)
                                       REFERENCES alojamiento (id_alojamiento),
  -- Dos habitaciones del mismo alojamiento no pueden compartir número.
  CONSTRAINT uq_habitacion_numero      UNIQUE (id_alojamiento, numero),
  -- Llave candidata (habitación, alojamiento): la usan las FK compuestas de
  -- RESERVA_HABITACION para garantizar que la habitación sea del alojamiento
  -- de la reserva (ver decisión de diseño 1).
  CONSTRAINT uq_habitacion_aloj        UNIQUE (id_habitacion, id_alojamiento),
  CONSTRAINT ck_habitacion_tipo        CHECK (tipo_habitacion IN ('SENCILLA','DOBLE','SUITE','CABANA')),
  CONSTRAINT ck_habitacion_capacidad   CHECK (capacidad_maxima BETWEEN 1 AND 12),
  CONSTRAINT ck_habitacion_activa      CHECK (activa IN ('S','N'))
);
COMMENT ON TABLE  habitacion                  IS 'Unidad reservable de un alojamiento (habitación, suite, cabaña o domo).';
COMMENT ON COLUMN habitacion.numero           IS 'Identificador visible dentro del alojamiento (101, H3, D02...). Único por alojamiento.';
COMMENT ON COLUMN habitacion.capacidad_maxima IS 'Número máximo de huéspedes que admite.';

/* =============================================================================
   3. PRECIOS: TEMPORADAS, CALENDARIO Y TARIFAS  (decisión de diseño 2)
   ============================================================================= */

-- 3.1 TEMPORADA: un periodo concreto de un año con categoría ALTA/MEDIA/BAJA.
--     "Semana Santa 2025" y "Semana Santa 2026" son filas distintas.
CREATE TABLE temporada (
  id_temporada  NUMBER(5)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre        VARCHAR2(80)  NOT NULL,
  categoria     VARCHAR2(5)   NOT NULL,
  anio          NUMBER(4)     NOT NULL,
  fecha_inicio  DATE          NOT NULL,
  fecha_fin     DATE          NOT NULL,
  CONSTRAINT pk_temporada            PRIMARY KEY (id_temporada),
  CONSTRAINT uq_temporada_nombre     UNIQUE (anio, nombre),
  CONSTRAINT uq_temporada_inicio     UNIQUE (fecha_inicio),
  CONSTRAINT ck_temporada_categoria  CHECK (categoria IN ('ALTA','MEDIA','BAJA')),
  CONSTRAINT ck_temporada_rango      CHECK (fecha_fin >= fecha_inicio),
  CONSTRAINT ck_temporada_dias       CHECK (fecha_inicio = TRUNC(fecha_inicio) AND fecha_fin = TRUNC(fecha_fin)),
  -- Las temporadas se definen por año: no pueden cruzar el 31 de diciembre.
  CONSTRAINT ck_temporada_anio       CHECK (EXTRACT(YEAR FROM fecha_inicio) = anio
                                            AND EXTRACT(YEAR FROM fecha_fin) = anio)
);
COMMENT ON TABLE  temporada           IS 'Periodo de un año con una categoría tarifaria (alta, media, baja). Las temporadas de un año cubren todos sus días sin solaparse.';
COMMENT ON COLUMN temporada.categoria IS 'ALTA: Semana Santa, mitad de año, puentes festivos, diciembre-enero. MEDIA y BAJA: el resto.';

-- 3.2 CALENDARIO (entidad agregada): una fila por día, con la temporada vigente.
--     La PK sobre la fecha garantiza que un día pertenece a UNA sola temporada,
--     así que dos temporadas no pueden solaparse. Es la pieza que permite
--     valorar una estadía noche por noche (fn_valor_estadia, Entrega 2) y
--     calcular la ocupación por mes.
CREATE TABLE calendario (
  fecha            DATE        NOT NULL,
  id_temporada     NUMBER(5)   NOT NULL,
  anio             NUMBER(4)   NOT NULL,
  mes              NUMBER(2)   NOT NULL,
  dia_semana       NUMBER(1)   NOT NULL,
  es_fin_de_semana CHAR(1)     NOT NULL,
  CONSTRAINT pk_calendario            PRIMARY KEY (fecha),
  CONSTRAINT fk_calendario_temporada  FOREIGN KEY (id_temporada)
                                      REFERENCES temporada (id_temporada),
  CONSTRAINT ck_calendario_dia        CHECK (fecha = TRUNC(fecha)),
  CONSTRAINT ck_calendario_mes        CHECK (mes BETWEEN 1 AND 12),
  CONSTRAINT ck_calendario_dsem       CHECK (dia_semana BETWEEN 1 AND 7),
  CONSTRAINT ck_calendario_finde      CHECK (es_fin_de_semana IN ('S','N'))
);
COMMENT ON TABLE  calendario            IS 'Dimensión de fechas: un día = una fila = una temporada. Se deriva de los rangos de TEMPORADA. Entidad agregada.';
COMMENT ON COLUMN calendario.dia_semana IS 'Día ISO: 1 = lunes ... 7 = domingo (independiente de la configuración NLS).';

-- 3.3 TARIFA: valor por noche de una habitación en una temporada.
CREATE TABLE tarifa (
  id_tarifa           NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_habitacion       NUMBER(8)      NOT NULL,
  id_temporada        NUMBER(5)      NOT NULL,
  valor_noche         NUMBER(12,2)   NOT NULL,
  fecha_actualizacion DATE           DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_tarifa             PRIMARY KEY (id_tarifa),
  CONSTRAINT fk_tarifa_habitacion  FOREIGN KEY (id_habitacion)
                                   REFERENCES habitacion (id_habitacion),
  CONSTRAINT fk_tarifa_temporada   FOREIGN KEY (id_temporada)
                                   REFERENCES temporada (id_temporada),
  -- Una sola tarifa por cada combinación habitación × temporada.
  CONSTRAINT uq_tarifa_hab_temp    UNIQUE (id_habitacion, id_temporada),
  CONSTRAINT ck_tarifa_valor       CHECK (valor_noche > 0)
);
COMMENT ON TABLE  tarifa             IS 'Precio por noche de cada habitación en cada temporada. No es un porcentaje sobre un precio base: cada alojamiento fija su valor.';
COMMENT ON COLUMN tarifa.valor_noche IS 'Pesos colombianos (COP) por noche.';

