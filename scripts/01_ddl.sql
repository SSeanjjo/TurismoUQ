-- 1.1 MUNICIPIO: los 12 municipios del Quindío (código DANE 63xxx).
CREATE TABLE municipio (
  id_municipio   NUMBER(4)      GENERATED BY DEFAULT ON NULL AS IDENTITY,
  codigo_dane    CHAR(5)        NOT NULL,
  nombre         VARCHAR2(60)   NOT NULL,
  CONSTRAINT pk_municipio        PRIMARY KEY (id_municipio),
  CONSTRAINT uq_municipio_dane   UNIQUE (codigo_dane),
  CONSTRAINT uq_municipio_nombre UNIQUE (nombre),
  CONSTRAINT ck_municipio_dane   CHECK (codigo_dane LIKE '63___')
);
COMMENT ON TABLE  municipio             IS 'Municipios del departamento del Quindío donde se ubican los alojamientos.';
COMMENT ON COLUMN municipio.codigo_dane IS 'Código DANE de 5 dígitos; todos los del Quindío empiezan por 63.';

-- 1.2 TIPO_ALOJAMIENTO: finca cafetera, hotel, glamping, hostal, ecohotel.
CREATE TABLE tipo_alojamiento (
  id_tipo_alojamiento NUMBER(3)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre              VARCHAR2(40)  NOT NULL,
  descripcion         VARCHAR2(300),
  CONSTRAINT pk_tipo_alojamiento        PRIMARY KEY (id_tipo_alojamiento),
  CONSTRAINT uq_tipo_alojamiento_nombre UNIQUE (nombre)
);
COMMENT ON TABLE tipo_alojamiento IS 'Clasificación comercial del alojamiento (finca cafetera, hotel, glamping, hostal, ecohotel).';

-- 1.3 CIUDAD (entidad agregada): ciudad de origen de los clientes.
--     Se separa de MUNICIPIO porque los clientes vienen de todo el país y del
--     exterior; normalizarla evita escribir "Bogota", "Bogotá", "BOGOTA D.C."
--     y permite analizar el origen de los turistas.
CREATE TABLE ciudad (
  id_ciudad      NUMBER(5)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre         VARCHAR2(60)  NOT NULL,
  departamento   VARCHAR2(60),
  pais           VARCHAR2(40)  DEFAULT 'Colombia' NOT NULL,
  CONSTRAINT pk_ciudad            PRIMARY KEY (id_ciudad),
  CONSTRAINT uq_ciudad_nombre_pais UNIQUE (nombre, pais)
);
COMMENT ON TABLE  ciudad              IS 'Ciudades de origen de los clientes (nacionales e internacionales). Entidad agregada al modelo mínimo.';
COMMENT ON COLUMN ciudad.departamento IS 'Departamento, estado o provincia; nulo cuando no aplica.';

/* =============================================================================
   2. OFERTA: ALOJAMIENTOS Y HABITACIONES
