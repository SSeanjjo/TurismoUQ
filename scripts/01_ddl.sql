/* -----------------------------------------------------------------------------
   0. Limpieza: elimina las tablas si ya existen (ignora ORA-00942 / ORA-00942
      "la tabla no existe") para que el script sea re-ejecutable.
   ----------------------------------------------------------------------------- */
BEGIN
  FOR t IN (SELECT column_value AS nombre
              FROM TABLE(sys.odcivarchar2list(
                     'RESENA','PAGO','RESERVA_SERVICIO','SERVICIO','RESERVA_HABITACION',
                     'RESERVA','USUARIO_SISTEMA','CLIENTE','TARIFA','CALENDARIO',
                     'TEMPORADA','HABITACION','ALOJAMIENTO','CIUDAD',
                     'TIPO_ALOJAMIENTO','MUNICIPIO'))) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.nombre || ' CASCADE CONSTRAINTS PURGE';
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
    END;
  END LOOP;
  BEGIN
    EXECUTE IMMEDIATE 'DROP VIEW vw_valor_reserva';
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE != -942 THEN RAISE; END IF;
  END;
END;
