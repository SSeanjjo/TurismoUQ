/* -----------------------------------------------------------------------------
   1. LIQUIDACION_MENSUAL: resultado del proceso masivo del cursor.
      Una fila por alojamiento y mes: lo que la plataforma le liquida al
      alojamiento por las estadías terminadas ese mes, menos su comisión.
   ----------------------------------------------------------------------------- */
CREATE TABLE liquidacion_mensual (
  id_liquidacion        NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_alojamiento        NUMBER(6)     NOT NULL,
  anio                  NUMBER(4)     NOT NULL,
  mes                   NUMBER(2)     NOT NULL,
  reservas              NUMBER(6)     NOT NULL,
  noches                NUMBER(7)     NOT NULL,
  ingreso_estadia       NUMBER(14,2)  NOT NULL,
  ingreso_servicios     NUMBER(14,2)  NOT NULL,
  ingreso_cancelaciones NUMBER(14,2)  NOT NULL,
  total_bruto           NUMBER(14,2)  NOT NULL,
  comision_plataforma   NUMBER(14,2)  NOT NULL,
  neto_alojamiento      NUMBER(14,2)  NOT NULL,
  fecha_generacion      DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_liquidacion          PRIMARY KEY (id_liquidacion),
  CONSTRAINT fk_liquidacion_aloj     FOREIGN KEY (id_alojamiento)
                                     REFERENCES alojamiento (id_alojamiento),
  CONSTRAINT uq_liquidacion_periodo  UNIQUE (id_alojamiento, anio, mes),
  CONSTRAINT ck_liquidacion_mes      CHECK (mes BETWEEN 1 AND 12),
  CONSTRAINT ck_liquidacion_neto     CHECK (neto_alojamiento = total_bruto - comision_plataforma)
);
COMMENT ON TABLE  liquidacion_mensual IS 'Liquidación mensual por alojamiento generada por pkg_reservas.sp_liquidacion_mensual (cursor explícito con parámetros).';
COMMENT ON COLUMN liquidacion_mensual.ingreso_estadia       IS 'Valor congelado de las estadías COMPLETADAS cuyo check-out cae en el mes.';
COMMENT ON COLUMN liquidacion_mensual.ingreso_cancelaciones IS 'Dinero retenido de reservas canceladas en el mes (sin reembolso, o el 20 % no reembolsado).';

/* =============================================================================
   2. ESPECIFICACIÓN DEL PAQUETE
   ============================================================================= */
CREATE OR REPLACE PACKAGE pkg_reservas AS

  -- Comisión que cobra la plataforma sobre lo liquidado a cada alojamiento.
  c_comision CONSTANT NUMBER := 0.12;

  -- Excepciones con nombre: quien llame puede capturarlas por nombre
  -- (WHEN pkg_reservas.e_no_disponible THEN ...) en lugar del número.
  e_no_disponible      EXCEPTION;  PRAGMA EXCEPTION_INIT(e_no_disponible,      -20101);
  e_fechas_invalidas   EXCEPTION;  PRAGMA EXCEPTION_INIT(e_fechas_invalidas,   -20102);
  e_capacidad_excedida EXCEPTION;  PRAGMA EXCEPTION_INIT(e_capacidad_excedida, -20103);
  e_habitacion         EXCEPTION;  PRAGMA EXCEPTION_INIT(e_habitacion,         -20104);
  e_cliente            EXCEPTION;  PRAGMA EXCEPTION_INIT(e_cliente,            -20105);
  e_sin_tarifa         EXCEPTION;  PRAGMA EXCEPTION_INIT(e_sin_tarifa,         -20106);

  /* Valor de una estadía: suma, noche por noche, de la tarifa de la temporada
     vigente cada noche. La noche d se cobra si fecha_in <= d < fecha_out
     (el día de salida no se cobra). Se puede usar desde SQL. */
  FUNCTION fn_valor_estadia (
    p_id_habitacion IN habitacion.id_habitacion%TYPE,
    p_fecha_in      IN DATE,
    p_fecha_out     IN DATE
  ) RETURN NUMBER;

  /* Imprime con DBMS_OUTPUT cada noche, su temporada y su tarifa. */
  PROCEDURE sp_detalle_estadia (
    p_id_habitacion IN habitacion.id_habitacion%TYPE,
    p_fecha_in      IN DATE,
    p_fecha_out     IN DATE
  );

  /* 'S' si la habitación no tiene reservas activas (no canceladas) que se
     crucen con [fecha_in, fecha_out); 'N' en caso contrario. */
  FUNCTION fn_disponible (
    p_id_habitacion IN habitacion.id_habitacion%TYPE,
    p_fecha_in      IN DATE,
    p_fecha_out     IN DATE
  ) RETURN VARCHAR2;

  /* Crea una reserva PENDIENTE con su primera habitación. No hace COMMIT:
     la transacción la controla quien llama (así se puede combinar con el
     pago en una sola transacción, Entrega 3). Ante cualquier error deshace
     solo su propio trabajo (ROLLBACK TO SAVEPOINT) y propaga el error. */
  PROCEDURE sp_crear_reserva (
    p_id_cliente    IN  cliente.id_cliente%TYPE,
    p_id_habitacion IN  habitacion.id_habitacion%TYPE,
    p_fecha_in      IN  DATE,
    p_fecha_out     IN  DATE,
    p_num_huespedes IN  NUMBER,
    p_id_reserva    OUT reserva.id_reserva%TYPE
  );

  /* Agrega otra habitación del mismo alojamiento a una reserva existente
     (grupos); sus fechas pueden diferir y amplían el rango general. */
  PROCEDURE sp_agregar_habitacion (
    p_id_reserva    IN reserva.id_reserva%TYPE,
    p_id_habitacion IN habitacion.id_habitacion%TYPE,
    p_fecha_in      IN DATE,
    p_fecha_out     IN DATE,
    p_num_huespedes IN NUMBER
  );

  /* Proceso masivo: recorre con un cursor explícito con parámetros todos los
     alojamientos (o uno) y genera su liquidación del mes en
     LIQUIDACION_MENSUAL. Re-ejecutable: reemplaza la del mismo periodo.
     Hace COMMIT al final (es un proceso por lotes). */
  PROCEDURE sp_liquidacion_mensual (
    p_anio           IN NUMBER,
    p_mes            IN NUMBER,
    p_id_alojamiento IN alojamiento.id_alojamiento%TYPE DEFAULT NULL
  );

END pkg_reservas;
/

/* =============================================================================
   3. CUERPO DEL PAQUETE
   ============================================================================= */
CREATE OR REPLACE PACKAGE BODY pkg_reservas AS

  /* ---------------------------------------------------------------------------
     Cursor explícito con parámetros de la liquidación mensual (privado).
     Regla de negocio: el alojamiento se liquida cuando la estadía TERMINA,
     así que entran las reservas COMPLETADAS con check-out dentro del mes,
     valoradas con los importes congelados al reservar (valor_estadia y
     precio_unitario), no con las tarifas actuales. Se suma el dinero
     retenido por cancelaciones hechas en el mes.
     LEFT JOIN: aparecen todos los alojamientos, también los que no
     facturaron (liquidación en cero).
     --------------------------------------------------------------------------- */
  CURSOR c_liquidacion (
    p_ini     DATE,
    p_fin     DATE,
    p_id_aloj NUMBER
  ) IS
    SELECT a.id_alojamiento,
           a.nombre_comercial,
           m.nombre                          AS municipio,
           NVL(e.reservas, 0)                AS reservas,
           NVL(e.noches, 0)                  AS noches,
           NVL(e.ingreso_estadia, 0)         AS ingreso_estadia,
           NVL(s.ingreso_servicios, 0)       AS ingreso_servicios,
           NVL(c.ingreso_cancelaciones, 0)   AS ingreso_cancelaciones
      FROM alojamiento a
      JOIN municipio m ON m.id_municipio = a.id_municipio
      LEFT JOIN (SELECT r.id_alojamiento,
                        COUNT(DISTINCT r.id_reserva)              AS reservas,
                        SUM(rh.fecha_checkout - rh.fecha_checkin) AS noches,
                        SUM(rh.valor_estadia)                     AS ingreso_estadia
                   FROM reserva r
                   JOIN reserva_habitacion rh ON rh.id_reserva = r.id_reserva
                  WHERE r.estado = 'COMPLETADA'
                    AND r.fecha_checkout BETWEEN p_ini AND p_fin
                  GROUP BY r.id_alojamiento) e
             ON e.id_alojamiento = a.id_alojamiento
      LEFT JOIN (SELECT r.id_alojamiento, SUM(rs.subtotal) AS ingreso_servicios
                   FROM reserva r
                   JOIN reserva_servicio rs ON rs.id_reserva = r.id_reserva
                  WHERE r.estado = 'COMPLETADA'
                    AND r.fecha_checkout BETWEEN p_ini AND p_fin
                  GROUP BY r.id_alojamiento) s
             ON s.id_alojamiento = a.id_alojamiento
      LEFT JOIN (SELECT r.id_alojamiento,
                        SUM(CASE WHEN p.estado = 'EXITOSO' THEN p.monto
                                 ELSE p.monto - p.monto_reembolsado END) AS ingreso_cancelaciones
                   FROM reserva r
                   JOIN pago p ON p.id_reserva = r.id_reserva
                  WHERE r.estado = 'CANCELADA'
                    AND p.estado IN ('EXITOSO', 'REEMBOLSADO')
                    AND r.fecha_cancelacion BETWEEN p_ini AND p_fin
                  GROUP BY r.id_alojamiento) c
             ON c.id_alojamiento = a.id_alojamiento
     WHERE p_id_aloj IS NULL OR a.id_alojamiento = p_id_aloj
     ORDER BY m.nombre, a.nombre_comercial;

  /* ---------------------------------------------------------------------------
     fn_valor_estadia  (decisión de diseño 2 de la Entrega 1)
     CALENDARIO asigna cada día a una temporada y TARIFA da el valor de esa
     habitación en esa temporada; sumar por día resuelve las estadías que
     cruzan temporadas (y años) sin lógica especial para el corte.
     Si alguna noche no tiene tarifa (fecha fuera del calendario cargado) no
     se devuelve un valor incompleto: se lanza -20106.
     --------------------------------------------------------------------------- */
  FUNCTION fn_valor_estadia (
    p_id_habitacion IN habitacion.id_habitacion%TYPE,
    p_fecha_in      IN DATE,
    p_fecha_out     IN DATE
  ) RETURN NUMBER IS
    v_in            DATE := TRUNC(p_fecha_in);
    v_out           DATE := TRUNC(p_fecha_out);
    v_noches        PLS_INTEGER;
    v_noches_tarifa PLS_INTEGER;
    v_total         NUMBER;
    v_existe        PLS_INTEGER;
  BEGIN
    IF p_id_habitacion IS NULL OR p_fecha_in IS NULL OR p_fecha_out IS NULL THEN
      RAISE_APPLICATION_ERROR(-20109, 'Habitación, fecha de entrada y fecha de salida son obligatorias.');
    END IF;
    IF v_out <= v_in THEN
      RAISE_APPLICATION_ERROR(-20102, 'El check-out (' || TO_CHAR(v_out, 'YYYY-MM-DD')
        || ') debe ser posterior al check-in (' || TO_CHAR(v_in, 'YYYY-MM-DD') || ').');
    END IF;

    SELECT COUNT(*) INTO v_existe FROM habitacion WHERE id_habitacion = p_id_habitacion;
    IF v_existe = 0 THEN
      RAISE_APPLICATION_ERROR(-20104, 'La habitación ' || p_id_habitacion || ' no existe.');
    END IF;

    v_noches := v_out - v_in;

    SELECT COUNT(*), NVL(SUM(t.valor_noche), 0)
      INTO v_noches_tarifa, v_total
      FROM calendario c
      JOIN tarifa t
        ON t.id_temporada  = c.id_temporada
       AND t.id_habitacion = p_id_habitacion
     WHERE c.fecha >= v_in
       AND c.fecha <  v_out;

    IF v_noches_tarifa < v_noches THEN
      RAISE_APPLICATION_ERROR(-20106, 'Solo ' || v_noches_tarifa || ' de ' || v_noches
        || ' noches tienen tarifa: el rango sale del calendario de temporadas cargado.');
    END IF;

    RETURN v_total;
  END fn_valor_estadia;

  /* --------------------------------------------------------------------------- */
  PROCEDURE sp_detalle_estadia (
    p_id_habitacion IN habitacion.id_habitacion%TYPE,
    p_fecha_in      IN DATE,
    p_fecha_out     IN DATE
  ) IS
    v_acumulado NUMBER := 0;
  BEGIN
    DBMS_OUTPUT.PUT_LINE('Habitación ' || p_id_habitacion || ' · '
      || TO_CHAR(p_fecha_in, 'YYYY-MM-DD') || ' -> ' || TO_CHAR(p_fecha_out, 'YYYY-MM-DD'));
    DBMS_OUTPUT.PUT_LINE(RPAD('Noche', 12) || RPAD('Cat.', 7) || RPAD('Temporada', 46)
      || LPAD('Tarifa', 12) || LPAD('Acumulado', 14));
    FOR n IN (SELECT c.fecha, te.categoria, te.nombre, t.valor_noche
                FROM calendario c
                JOIN temporada te ON te.id_temporada = c.id_temporada
                JOIN tarifa t     ON t.id_temporada  = c.id_temporada
                                 AND t.id_habitacion = p_id_habitacion
               WHERE c.fecha >= TRUNC(p_fecha_in)
                 AND c.fecha <  TRUNC(p_fecha_out)
               ORDER BY c.fecha) LOOP
      v_acumulado := v_acumulado + n.valor_noche;
      DBMS_OUTPUT.PUT_LINE(RPAD(TO_CHAR(n.fecha, 'YYYY-MM-DD'), 12) || RPAD(n.categoria, 7)
        || RPAD(n.nombre, 46) || LPAD(TO_CHAR(n.valor_noche, 'FM999G999G999G990'), 12)
        || LPAD(TO_CHAR(v_acumulado, 'FM999G999G999G990'), 14));
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('fn_valor_estadia = '
      || TO_CHAR(fn_valor_estadia(p_id_habitacion, p_fecha_in, p_fecha_out), 'FM999G999G999G990'));
  END sp_detalle_estadia;

  /* --------------------------------------------------------------------------- */
  FUNCTION fn_disponible (
    p_id_habitacion IN habitacion.id_habitacion%TYPE,
    p_fecha_in      IN DATE,
    p_fecha_out     IN DATE
  ) RETURN VARCHAR2 IS
    v_cruces PLS_INTEGER;
  BEGIN
    SELECT COUNT(*)
      INTO v_cruces
      FROM reserva_habitacion rh
      JOIN reserva r ON r.id_reserva = rh.id_reserva
     WHERE rh.id_habitacion = p_id_habitacion
       AND r.estado <> 'CANCELADA'
       AND rh.fecha_checkin  < TRUNC(p_fecha_out)
       AND TRUNC(p_fecha_in) < rh.fecha_checkout;
    RETURN CASE WHEN v_cruces = 0 THEN 'S' ELSE 'N' END;
  END fn_disponible;

  /* ---------------------------------------------------------------------------
     validar_linea (privado): reglas comunes a crear reserva y agregar
     habitación. Bloquea la fila de la habitación (FOR UPDATE) hasta el fin de
     la transacción: si dos sesiones intentan reservar la misma habitación al
     mismo tiempo, la segunda espera y luego ve la reserva de la primera
     (base del experimento de concurrencia de la Entrega 3).
     --------------------------------------------------------------------------- */
  PROCEDURE validar_linea (
    p_id_habitacion  IN  habitacion.id_habitacion%TYPE,
    p_fecha_in       IN  DATE,
    p_fecha_out      IN  DATE,
    p_num_huespedes  IN  NUMBER,
    p_id_alojamiento OUT alojamiento.id_alojamiento%TYPE
  ) IS
    v_capacidad  habitacion.capacidad_maxima%TYPE;
    v_activa     habitacion.activa%TYPE;
    v_conflicto  reserva.id_reserva%TYPE;
    v_conf_in    DATE;
    v_conf_out   DATE;
  BEGIN
    IF p_id_habitacion IS NULL OR p_fecha_in IS NULL OR p_fecha_out IS NULL THEN
      RAISE_APPLICATION_ERROR(-20109, 'Habitación, fecha de entrada y fecha de salida son obligatorias.');
    END IF;

    -- (1) fechas
    IF TRUNC(p_fecha_out) <= TRUNC(p_fecha_in) THEN
      RAISE_APPLICATION_ERROR(-20102, 'El check-out (' || TO_CHAR(p_fecha_out, 'YYYY-MM-DD')
        || ') debe ser posterior al check-in (' || TO_CHAR(p_fecha_in, 'YYYY-MM-DD') || ').');
    END IF;
    IF TRUNC(p_fecha_in) < TRUNC(SYSDATE) THEN
      RAISE_APPLICATION_ERROR(-20107, 'No se puede reservar con check-in en el pasado ('
        || TO_CHAR(p_fecha_in, 'YYYY-MM-DD') || ').');
    END IF;
    IF p_num_huespedes IS NULL OR p_num_huespedes < 1 OR p_num_huespedes <> TRUNC(p_num_huespedes) THEN
      RAISE_APPLICATION_ERROR(-20108, 'El número de huéspedes debe ser un entero mayor que cero.');
    END IF;

    -- (2) habitación: existe, está activa; se bloquea su fila
    BEGIN
      SELECT id_alojamiento, capacidad_maxima, activa
        INTO p_id_alojamiento, v_capacidad, v_activa
        FROM habitacion
       WHERE id_habitacion = p_id_habitacion
         FOR UPDATE;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20104, 'La habitación ' || p_id_habitacion || ' no existe.');
    END;
    IF v_activa = 'N' THEN
      RAISE_APPLICATION_ERROR(-20104, 'La habitación ' || p_id_habitacion || ' está inactiva.');
    END IF;

    -- (3) capacidad
    IF p_num_huespedes > v_capacidad THEN
      RAISE_APPLICATION_ERROR(-20103, 'Capacidad excedida: ' || p_num_huespedes
        || ' huéspedes y la habitación ' || p_id_habitacion || ' admite máximo ' || v_capacidad || '.');
    END IF;

    -- (4) disponibilidad: ninguna reserva activa que comparta una noche
    SELECT MIN(rh.id_reserva)
      INTO v_conflicto
      FROM reserva_habitacion rh
      JOIN reserva r ON r.id_reserva = rh.id_reserva
     WHERE rh.id_habitacion = p_id_habitacion
       AND r.estado <> 'CANCELADA'
       AND rh.fecha_checkin  < TRUNC(p_fecha_out)
       AND TRUNC(p_fecha_in) < rh.fecha_checkout;
    IF v_conflicto IS NOT NULL THEN
      SELECT fecha_checkin, fecha_checkout INTO v_conf_in, v_conf_out
        FROM reserva_habitacion
       WHERE id_reserva = v_conflicto AND id_habitacion = p_id_habitacion;
      RAISE_APPLICATION_ERROR(-20101, 'Habitación ' || p_id_habitacion || ' no disponible del '
        || TO_CHAR(p_fecha_in, 'YYYY-MM-DD') || ' al ' || TO_CHAR(p_fecha_out, 'YYYY-MM-DD')
        || ': se cruza con la reserva ' || v_conflicto || ' ('
        || TO_CHAR(v_conf_in, 'YYYY-MM-DD') || ' a ' || TO_CHAR(v_conf_out, 'YYYY-MM-DD') || ').');
    END IF;
  END validar_linea;

  /* --------------------------------------------------------------------------- */
  PROCEDURE sp_crear_reserva (
    p_id_cliente    IN  cliente.id_cliente%TYPE,
    p_id_habitacion IN  habitacion.id_habitacion%TYPE,
    p_fecha_in      IN  DATE,
    p_fecha_out     IN  DATE,
    p_num_huespedes IN  NUMBER,
    p_id_reserva    OUT reserva.id_reserva%TYPE
  ) IS
    v_existe  PLS_INTEGER;
    v_id_aloj alojamiento.id_alojamiento%TYPE;
    v_valor   NUMBER;
    v_in      DATE := TRUNC(p_fecha_in);
    v_out     DATE := TRUNC(p_fecha_out);
  BEGIN
    SAVEPOINT sp_crear_reserva_ini;

    SELECT COUNT(*) INTO v_existe FROM cliente WHERE id_cliente = p_id_cliente;
    IF v_existe = 0 THEN
      RAISE_APPLICATION_ERROR(-20105, 'El cliente ' || p_id_cliente || ' no existe.');
    END IF;

    validar_linea(p_id_habitacion, v_in, v_out, p_num_huespedes, v_id_aloj);
    v_valor := fn_valor_estadia(p_id_habitacion, v_in, v_out);   -- puede lanzar -20106

    INSERT INTO reserva (id_cliente, id_alojamiento, fecha_reserva,
                         fecha_checkin, fecha_checkout, estado)
    VALUES (p_id_cliente, v_id_aloj, TRUNC(SYSDATE), v_in, v_out, 'PENDIENTE')
    RETURNING id_reserva INTO p_id_reserva;

    INSERT INTO reserva_habitacion (id_reserva, id_alojamiento, id_habitacion,
                                    fecha_checkin, fecha_checkout, num_huespedes, valor_estadia)
    VALUES (p_id_reserva, v_id_aloj, p_id_habitacion, v_in, v_out, p_num_huespedes, v_valor);

  EXCEPTION
    WHEN OTHERS THEN
      ROLLBACK TO sp_crear_reserva_ini;   -- deshace solo lo de este procedimiento
      p_id_reserva := NULL;
      RAISE;                              -- conserva el código y el mensaje
  END sp_crear_reserva;

  /* --------------------------------------------------------------------------- */
  PROCEDURE sp_agregar_habitacion (
    p_id_reserva    IN reserva.id_reserva%TYPE,
    p_id_habitacion IN habitacion.id_habitacion%TYPE,
    p_fecha_in      IN DATE,
    p_fecha_out     IN DATE,
    p_num_huespedes IN NUMBER
  ) IS
    v_aloj_reserva alojamiento.id_alojamiento%TYPE;
    v_estado       reserva.estado%TYPE;
    v_id_aloj      alojamiento.id_alojamiento%TYPE;
    v_valor        NUMBER;
    v_in           DATE := TRUNC(p_fecha_in);
    v_out          DATE := TRUNC(p_fecha_out);
  BEGIN
    SAVEPOINT sp_agregar_hab_ini;

    BEGIN
      SELECT id_alojamiento, estado INTO v_aloj_reserva, v_estado
        FROM reserva WHERE id_reserva = p_id_reserva
         FOR UPDATE;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20111, 'La reserva ' || p_id_reserva || ' no existe.');
    END;
    IF v_estado NOT IN ('PENDIENTE', 'CONFIRMADA') THEN
      RAISE_APPLICATION_ERROR(-20112, 'La reserva ' || p_id_reserva || ' está ' || v_estado
        || ' y no admite más habitaciones.');
    END IF;

    validar_linea(p_id_habitacion, v_in, v_out, p_num_huespedes, v_id_aloj);
    IF v_id_aloj <> v_aloj_reserva THEN
      RAISE_APPLICATION_ERROR(-20110, 'La habitación ' || p_id_habitacion
        || ' no pertenece al alojamiento de la reserva ' || p_id_reserva || '.');
    END IF;
    v_valor := fn_valor_estadia(p_id_habitacion, v_in, v_out);

    INSERT INTO reserva_habitacion (id_reserva, id_alojamiento, id_habitacion,
                                    fecha_checkin, fecha_checkout, num_huespedes, valor_estadia)
    VALUES (p_id_reserva, v_aloj_reserva, p_id_habitacion, v_in, v_out, p_num_huespedes, v_valor);

    -- El rango general de la reserva cubre todas sus líneas.
    UPDATE reserva
       SET fecha_checkin  = LEAST(fecha_checkin, v_in),
           fecha_checkout = GREATEST(fecha_checkout, v_out)
     WHERE id_reserva = p_id_reserva;

  EXCEPTION
    WHEN OTHERS THEN
      ROLLBACK TO sp_agregar_hab_ini;
      RAISE;
  END sp_agregar_habitacion;

  /* ---------------------------------------------------------------------------
     sp_liquidacion_mensual: OPEN / FETCH / CLOSE explícitos sobre el cursor
     parametrizado c_liquidacion. Por cada alojamiento calcula bruto,
     comisión y neto, lo guarda y lo imprime.
     --------------------------------------------------------------------------- */
  PROCEDURE sp_liquidacion_mensual (
    p_anio           IN NUMBER,
    p_mes            IN NUMBER,
    p_id_alojamiento IN alojamiento.id_alojamiento%TYPE DEFAULT NULL
  ) IS
    r            c_liquidacion%ROWTYPE;
    v_ini        DATE;
    v_fin        DATE;
    v_bruto      NUMBER;
    v_comision   NUMBER;
    v_neto       NUMBER;
    v_tot_bruto  NUMBER := 0;
    v_tot_com    NUMBER := 0;
    v_tot_neto   NUMBER := 0;
    v_filas      PLS_INTEGER := 0;
  BEGIN
    SAVEPOINT sp_liquidacion_ini;   -- primero: el manejador de errores vuelve aquí
    IF p_anio IS NULL OR p_mes IS NULL OR p_mes NOT BETWEEN 1 AND 12 THEN
      RAISE_APPLICATION_ERROR(-20113, 'Periodo inválido: año ' || p_anio || ', mes ' || p_mes || '.');
    END IF;
    v_ini := TO_DATE(TO_CHAR(p_anio) || '-' || LPAD(TO_CHAR(p_mes), 2, '0') || '-01', 'YYYY-MM-DD');
    v_fin := LAST_DAY(v_ini);

    -- Re-ejecutable: se reemplaza la liquidación del mismo periodo.
    DELETE FROM liquidacion_mensual
     WHERE anio = p_anio AND mes = p_mes
       AND (p_id_alojamiento IS NULL OR id_alojamiento = p_id_alojamiento);

    DBMS_OUTPUT.PUT_LINE('LIQUIDACIÓN ' || TO_CHAR(v_ini, 'YYYY-MM')
      || ' · comisión plataforma ' || (c_comision * 100) || ' %');
    DBMS_OUTPUT.PUT_LINE(RPAD('Municipio', 13) || RPAD('Alojamiento', 36) || LPAD('Res.', 6)
      || LPAD('Noches', 8) || LPAD('Bruto', 15) || LPAD('Comisión', 14) || LPAD('Neto', 15));

    OPEN c_liquidacion(v_ini, v_fin, p_id_alojamiento);
    LOOP
      FETCH c_liquidacion INTO r;
      EXIT WHEN c_liquidacion%NOTFOUND;

      v_bruto    := r.ingreso_estadia + r.ingreso_servicios + r.ingreso_cancelaciones;
      v_comision := ROUND(v_bruto * c_comision, 2);
      v_neto     := v_bruto - v_comision;

      INSERT INTO liquidacion_mensual
        (id_alojamiento, anio, mes, reservas, noches, ingreso_estadia, ingreso_servicios,
         ingreso_cancelaciones, total_bruto, comision_plataforma, neto_alojamiento)
      VALUES
        (r.id_alojamiento, p_anio, p_mes, r.reservas, r.noches, r.ingreso_estadia,
         r.ingreso_servicios, r.ingreso_cancelaciones, v_bruto, v_comision, v_neto);

      DBMS_OUTPUT.PUT_LINE(RPAD(r.municipio, 13) || RPAD(SUBSTR(r.nombre_comercial, 1, 35), 36)
        || LPAD(r.reservas, 6) || LPAD(r.noches, 8)
        || LPAD(TO_CHAR(v_bruto, 'FM999G999G999G990'), 15)
        || LPAD(TO_CHAR(v_comision, 'FM999G999G999G990'), 14)
        || LPAD(TO_CHAR(v_neto, 'FM999G999G999G990'), 15));

      v_tot_bruto := v_tot_bruto + v_bruto;
      v_tot_com   := v_tot_com + v_comision;
      v_tot_neto  := v_tot_neto + v_neto;
    END LOOP;
    v_filas := c_liquidacion%ROWCOUNT;
    CLOSE c_liquidacion;

    COMMIT;
    DBMS_OUTPUT.PUT_LINE(RPAD('TOTAL (' || v_filas || ' alojamientos)', 63)
      || LPAD(TO_CHAR(v_tot_bruto, 'FM999G999G999G990'), 15)
      || LPAD(TO_CHAR(v_tot_com, 'FM999G999G999G990'), 14)
      || LPAD(TO_CHAR(v_tot_neto, 'FM999G999G999G990'), 15));
  EXCEPTION
    WHEN OTHERS THEN
      IF c_liquidacion%ISOPEN THEN CLOSE c_liquidacion; END IF;   -- el cursor del paquete no queda abierto
      ROLLBACK TO sp_liquidacion_ini;
      RAISE;
  END sp_liquidacion_mensual;

END pkg_reservas;
