/* =============================================================================
   1. AUDITORÍA DE TARIFA
   ============================================================================= */

-- 1.1 Número de sentencia: todas las filas cambiadas por un mismo UPDATE
--     comparten id_sentencia, así se reconstruye qué cambió cada sentencia.
CREATE SEQUENCE seq_auditoria_sentencia START WITH 1 INCREMENT BY 1 NOCACHE;

-- 1.2 Tabla de auditoría (solo se inserta; nunca se actualiza).
CREATE TABLE auditoria_tarifa (
  id_auditoria      NUMBER(12)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_sentencia      NUMBER(10)     NOT NULL,
  operacion         VARCHAR2(6)    NOT NULL,
  id_tarifa         NUMBER(10)     NOT NULL,
  id_habitacion     NUMBER(8)      NOT NULL,
  id_temporada      NUMBER(5)      NOT NULL,
  valor_anterior    NUMBER(12,2),
  valor_nuevo       NUMBER(12,2),
  usuario_bd        VARCHAR2(128)  NOT NULL,
  usuario_so        VARCHAR2(128),
  equipo            VARCHAR2(128),
  programa          VARCHAR2(128),
  fecha_hora        TIMESTAMP      NOT NULL,
  filas_sentencia   NUMBER(8)      NOT NULL,
  CONSTRAINT pk_auditoria_tarifa  PRIMARY KEY (id_auditoria),
  CONSTRAINT ck_auditoria_oper    CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE')),
  CONSTRAINT ck_auditoria_valores CHECK (
       (operacion = 'INSERT' AND valor_anterior IS NULL     AND valor_nuevo IS NOT NULL)
    OR (operacion = 'UPDATE' AND valor_anterior IS NOT NULL AND valor_nuevo IS NOT NULL)
    OR (operacion = 'DELETE' AND valor_anterior IS NOT NULL AND valor_nuevo IS NULL))
);
-- Sin FK a TARIFA a propósito: la auditoría debe sobrevivir aunque la tarifa
-- se borre (precisamente un DELETE es algo que hay que poder auditar).
COMMENT ON TABLE  auditoria_tarifa              IS 'Bitácora de cambios de TARIFA escrita por trg_auditoria_tarifa: quién, cuándo, valor anterior y nuevo.';
COMMENT ON COLUMN auditoria_tarifa.usuario_bd   IS 'Usuario Oracle que ejecutó la sentencia (USER).';
COMMENT ON COLUMN auditoria_tarifa.usuario_so   IS 'Usuario del sistema operativo del cliente (SYS_CONTEXT USERENV OS_USER).';
COMMENT ON COLUMN auditoria_tarifa.id_sentencia IS 'Agrupa todas las filas modificadas por una misma sentencia.';

/* -----------------------------------------------------------------------------
   1.3 trg_auditoria_tarifa · disparador de SENTENCIA
   Un disparador de sentencia (BEFORE/AFTER STATEMENT) se ejecuta una vez por
   UPDATE, sin importar cuántas filas cambie, y NO puede leer :OLD ni :NEW
   (esos valores solo existen fila a fila). Para registrar el valor anterior y
   el nuevo usamos un disparador COMPUESTO (COMPOUND TRIGGER), que reúne en un
   solo objeto los momentos de sentencia y de fila y comparte variables entre
   ellos:
     BEFORE STATEMENT  se abre la "sentencia auditada": número de sentencia,
                       usuario, equipo y hora (una sola vez).
     AFTER EACH ROW    solo GUARDA EN MEMORIA :OLD y :NEW de cada fila.
     AFTER STATEMENT   escribe la auditoría: una vez, al final de la sentencia,
                       todas las filas juntas.
   Ventajas frente a escribir la auditoría fila a fila: la hora y el usuario
   son los de la sentencia, se sabe cuántas filas cambió cada sentencia
   (filas_sentencia) y la escritura ocurre una sola vez por sentencia.
   ----------------------------------------------------------------------------- */
CREATE OR REPLACE TRIGGER trg_auditoria_tarifa
  FOR INSERT OR UPDATE OF valor_noche OR DELETE ON tarifa
  COMPOUND TRIGGER

  TYPE t_cambios IS TABLE OF auditoria_tarifa%ROWTYPE INDEX BY PLS_INTEGER;
  v_cambios    t_cambios;
  v_sentencia  NUMBER;
  v_usuario    VARCHAR2(128);
  v_usuario_so VARCHAR2(128);
  v_equipo     VARCHAR2(128);
  v_programa   VARCHAR2(128);
  v_momento    TIMESTAMP;
  -- Las secciones de tiempo de un disparador compuesto no admiten
  -- declaraciones propias: sus variables se declaran aquí.
  i            PLS_INTEGER;
  v_fila       auditoria_tarifa%ROWTYPE;
  v_registrar  BOOLEAN;

  -- -------------------------------------------------------- nivel de sentencia
  BEFORE STATEMENT IS
  BEGIN
    v_cambios.DELETE;
    v_sentencia  := seq_auditoria_sentencia.NEXTVAL;
    v_usuario    := USER;
    v_usuario_so := SYS_CONTEXT('USERENV', 'OS_USER');
    v_equipo     := SYS_CONTEXT('USERENV', 'HOST');
    v_programa   := SYS_CONTEXT('USERENV', 'MODULE');
    v_momento    := SYSTIMESTAMP;
  END BEFORE STATEMENT;

  -- -------------------------------------------------------- nivel de fila
  BEFORE EACH ROW IS
  BEGIN
    -- La tarifa guarda cuándo se actualizó por última vez.
    IF INSERTING OR UPDATING THEN
      :NEW.fecha_actualizacion := SYSDATE;
    END IF;
  END BEFORE EACH ROW;

  AFTER EACH ROW IS
  BEGIN
    -- Un UPDATE que deja el mismo valor no es un cambio: no se audita.
    IF UPDATING THEN
      v_registrar := :OLD.valor_noche <> :NEW.valor_noche;
    ELSE
      v_registrar := TRUE;
    END IF;

    IF v_registrar THEN
      i := v_cambios.COUNT + 1;
      v_cambios(i).id_sentencia   := v_sentencia;
      IF INSERTING THEN
        v_cambios(i).operacion := 'INSERT';
      ELSIF UPDATING THEN
        v_cambios(i).operacion := 'UPDATE';
      ELSE
        v_cambios(i).operacion := 'DELETE';
      END IF;
      v_cambios(i).id_tarifa      := NVL(:NEW.id_tarifa,     :OLD.id_tarifa);
      v_cambios(i).id_habitacion  := NVL(:NEW.id_habitacion, :OLD.id_habitacion);
      v_cambios(i).id_temporada   := NVL(:NEW.id_temporada,  :OLD.id_temporada);
      v_cambios(i).valor_anterior := :OLD.valor_noche;      -- NULL en INSERT
      v_cambios(i).valor_nuevo    := :NEW.valor_noche;      -- NULL en DELETE
    END IF;
  END AFTER EACH ROW;

  -- -------------------------------------------------------- nivel de sentencia
  AFTER STATEMENT IS
  BEGIN
    FOR k IN 1 .. v_cambios.COUNT LOOP
      v_fila := v_cambios(k);
      v_fila.id_auditoria    := NULL;              -- lo asigna IDENTITY
      v_fila.usuario_bd      := v_usuario;
      v_fila.usuario_so      := v_usuario_so;
      v_fila.equipo          := v_equipo;
      v_fila.programa        := v_programa;
      v_fila.fecha_hora      := v_momento;
      v_fila.filas_sentencia := v_cambios.COUNT;
      INSERT INTO auditoria_tarifa VALUES v_fila;
    END LOOP;
    v_cambios.DELETE;
  END AFTER STATEMENT;

END trg_auditoria_tarifa;
/

/* =============================================================================
   2. trg_rh_sin_solape · disparador de FILA
   Antes de insertar cada línea de RESERVA_HABITACION verifica que la misma
   habitación no tenga otra reserva activa (no cancelada) que comparta alguna
   noche. Dos estadías [in1, out1) y [in2, out2) se cruzan si
       in1 < out2  AND  in2 < out1
   así que el día de salida de una puede ser el de llegada de la siguiente.
   Una reserva PENDIENTE también bloquea: si no, dos pendientes de la misma
   habitación podrían confirmarse las dos.

   Es la segunda línea de defensa: pkg_reservas.sp_crear_reserva ya valida la
   disponibilidad, pero el disparador protege también los INSERT que no pasen
   por el paquete (otra aplicación, un script, un error de programación).

   Por qué solo INSERT: un disparador de fila no puede consultar la misma tabla
   que se está modificando (ORA-04091, tabla mutante), salvo en un INSERT de
   una sola fila con VALUES, que es justo como insertan sp_crear_reserva y
   sp_agregar_habitacion. Un INSERT ... SELECT o un UPDATE de fechas sobre
   esta tabla sí daría ORA-04091; los cambios de fechas se hacen anulando la
   línea y creando otra con el procedimiento.
   ============================================================================= */
CREATE OR REPLACE TRIGGER trg_rh_sin_solape
  BEFORE INSERT ON reserva_habitacion
  FOR EACH ROW
DECLARE
  v_estado     reserva.estado%TYPE;
  v_conflicto  reserva.id_reserva%TYPE;
BEGIN
  -- Estado de la reserva a la que pertenece la nueva línea.
  BEGIN
    SELECT estado INTO v_estado FROM reserva WHERE id_reserva = :NEW.id_reserva;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      v_estado := NULL;   -- la FK rechazará la fila con su propio error
  END;

  -- Una reserva cancelada no ocupa la habitación: no hay nada que validar.
  IF v_estado IS NOT NULL AND v_estado <> 'CANCELADA' THEN
    SELECT MIN(rh.id_reserva)
      INTO v_conflicto
      FROM reserva_habitacion rh
      JOIN reserva r ON r.id_reserva = rh.id_reserva
     WHERE rh.id_habitacion = :NEW.id_habitacion
       AND rh.id_reserva   <> :NEW.id_reserva
       AND r.estado        <> 'CANCELADA'
       AND rh.fecha_checkin  < :NEW.fecha_checkout
       AND :NEW.fecha_checkin < rh.fecha_checkout;

    IF v_conflicto IS NOT NULL THEN
      RAISE_APPLICATION_ERROR(-20120,
        'trg_rh_sin_solape: la habitación ' || :NEW.id_habitacion || ' ya está reservada entre el '
        || TO_CHAR(:NEW.fecha_checkin, 'YYYY-MM-DD') || ' y el '
        || TO_CHAR(:NEW.fecha_checkout, 'YYYY-MM-DD') || ' por la reserva ' || v_conflicto || '.');
    END IF;
  END IF;
END trg_rh_sin_solape;
/

/* =============================================================================
   3. trg_resena_completada · disparador de fila (adicional)
   Regla R2 de la Entrega 1: solo se reseña una reserva COMPLETADA. La FK y el
   UNIQUE ya garantizan que la reseña viene de una reserva y que hay máximo
   una; el estado está en otra tabla y por eso lo valida un disparador.
   ============================================================================= */
CREATE OR REPLACE TRIGGER trg_resena_completada
  BEFORE INSERT OR UPDATE OF id_reserva ON resena
  FOR EACH ROW
DECLARE
  v_estado reserva.estado%TYPE;
BEGIN
  SELECT estado INTO v_estado FROM reserva WHERE id_reserva = :NEW.id_reserva;
  IF v_estado <> 'COMPLETADA' THEN
    RAISE_APPLICATION_ERROR(-20121, 'Solo se puede reseñar una reserva COMPLETADA; la reserva '
      || :NEW.id_reserva || ' está ' || v_estado || '.');
  END IF;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    NULL;   -- reserva inexistente: la FK rechazará la fila
END trg_resena_completada;
/

/* -----------------------------------------------------------------------------
   4. Verificación: los tres disparadores deben quedar ENABLED y VALID.
   ----------------------------------------------------------------------------- */
SELECT t.trigger_name, t.trigger_type, t.triggering_event, t.table_name,
       t.status AS habilitado, o.status AS compilacion
  FROM user_triggers t
  JOIN user_objects  o ON o.object_name = t.trigger_name AND o.object_type = 'TRIGGER'
 WHERE t.trigger_name IN ('TRG_AUDITORIA_TARIFA', 'TRG_RH_SIN_SOLAPE', 'TRG_RESENA_COMPLETADA')
 ORDER BY t.trigger_name;

SELECT name, line, position, text
  FROM user_errors
 WHERE name IN ('TRG_AUDITORIA_TARIFA', 'TRG_RH_SIN_SOLAPE', 'TRG_RESENA_COMPLETADA')
 ORDER BY name, sequence;

